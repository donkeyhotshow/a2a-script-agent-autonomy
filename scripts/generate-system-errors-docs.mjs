#!/usr/bin/env node
/**
 * Regenerate docs/system-errors/*.generated.md from code sources.
 * Run from repo root: node scripts/generate-system-errors-docs.mjs
 * npm: npm run docs:system-errors
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, '..');
const OUT_DIR = path.join(REPO, 'docs', 'system-errors');

const BANNER = '<!-- AUTO-GENERATED by scripts/generate-system-errors-docs.mjs — do not edit -->\n\n';

function extractQuickFixes(errorsJs) {
  const start = errorsJs.indexOf('const fixes = {');
  if (start < 0) return {};
  const sub = errorsJs.slice(start);
  const end = sub.indexOf('\n    };');
  const body = sub.slice(0, end);
  const out = {};
  const re = /'([^']+:[^']+)':\s*'((?:\\'|[^'])*)'/g;
  let m;
  while ((m = re.exec(body))) {
    out[m[1]] = m[2].replace(/\\'/g, "'");
  }
  return out;
}

/** Next line (or same block) with fieldName: value — supports `...`, '...', or expression (ternary). */
function extractFieldAfterCode(filePath, fieldName) {
  const lines = fs.readFileSync(filePath, 'utf8').split(/\r?\n/);
  const rows = [];
  const fieldRe = new RegExp(`^\\s*${fieldName}:\\s*(.+)\\s*,?\\s*$`);
  for (let i = 0; i < lines.length; i++) {
    const cm = lines[i].match(/code:\s*'([A-Z0-9_]+)'/);
    if (!cm) continue;
    const code = cm[1];
    let raw = '';
    for (let j = i + 1; j < Math.min(i + 10, lines.length); j++) {
      const line = lines[j];
      const fm = line.match(fieldRe);
      if (fm) {
        raw = fm[1].trim().replace(/,\s*$/, '');
        break;
      }
    }
    let text = raw;
    const bt = raw.match(/^`([^`]*)`$/);
    if (bt) text = bt[1];
    else {
      const sq = raw.match(/^'((?:\\'|[^'])*)'$/);
      if (sq) text = sq[1].replace(/\\'/g, "'");
    }
    if (text.length > 200) text = `${text.slice(0, 197)}…`;
    rows.push({ code, text });
  }
  const seen = new Set();
  const deduped = [];
  for (const r of rows) {
    if (seen.has(r.code)) continue;
    seen.add(r.code);
    deduped.push(r);
  }
  return deduped;
}

function mdTable(headers, rows) {
  const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const h = `| ${headers.join(' | ')} |`;
  const sep = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => `| ${r.map(esc).join(' | ')} |`).join('\n');
  return `${h}\n${sep}\n${body}\n`;
}

async function main() {
  const { ErrorClassifier } = await import(pathToFileUrl(path.join(REPO, 'tests', 'monitor-tasks', 'errors.js')));
  const classifier = new ErrorClassifier();
  const patterns = classifier.errorPatterns;

  const errorsJsPath = path.join(REPO, 'tests', 'monitor-tasks', 'errors.js');
  const errorsJs = fs.readFileSync(errorsJsPath, 'utf8');
  const quickFixes = extractQuickFixes(errorsJs);

  const tsPath = path.join(
    REPO,
    'a2a-server',
    'src',
    'services',
    'core',
    'request-processor',
    'validators',
    'transform-execute-validator.ts'
  );
  const transformRows = extractFieldAfterCode(tsPath, 'message');

  const llmPath = path.join(REPO, 'tests', 'direct-tests', 'validators', 'lib', 'check-llm-execute-shape.mjs');
  const llmRows = extractFieldAfterCode(llmPath, 'detail');

  const generatedAt = new Date().toISOString();

  const monitorRows = patterns.map((p) => {
    const pat = p.pattern instanceof RegExp ? `/${p.pattern.source}/${p.pattern.flags}` : String(p.pattern);
    const key = `${p.type}:${p.subtype}`;
    const qf = quickFixes[key] || '';
    return [pat, p.type, p.subtype, p.severity || '', p.hint || '', qf];
  });

  const monitorMd =
    BANNER +
    `# Monitor ErrorClassifier (generated)\n\n` +
    `**Generated:** ${generatedAt}  \n**Source:** [\`tests/monitor-tasks/errors.js\`](../../tests/monitor-tasks/errors.js)\n\n` +
    `Regex patterns match \`error.message\` (and HTTP status when present). First match wins.\n\n` +
    mdTable(['Pattern', 'type', 'subtype', 'severity', 'hint', 'quickFix (if any)'], monitorRows) +
    `\n`;

  const transformMd =
    BANNER +
    `# Transform / execute / result codes (generated)\n\n` +
    `**Generated:** ${generatedAt}  \n**Source:** [\`transform-execute-validator.ts\`](../../a2a-server/src/services/core/request-processor/validators/transform-execute-validator.ts)\n\n` +
    `Strict mode: \`A2A_TRANSFORM_STRICT=1\`.\n\n` +
    mdTable(['Code', 'message'], transformRows.map((r) => [r.code, r.text])) +
    `\n`;

  const llmMd =
    BANNER +
    `# Offline LLM execute shape codes (generated)\n\n` +
    `**Generated:** ${generatedAt}  \n**Source:** [\`check-llm-execute-shape.mjs\`](../../tests/direct-tests/validators/lib/check-llm-execute-shape.mjs)\n\n` +
    `Used by \`scan-promise-bodies\`, \`scan-session-responses\`.\n\n` +
    mdTable(['Code', 'detail'], llmRows.map((r) => [r.code, r.text])) +
    `\n`;

  const validatorsRows = [
    ['npm run test:indirect', 'Mama indirect suite (registry, red/gray, audits)'],
    ['npm run test:server:unit', 'a2a-server Vitest (excl. integration/e2e)'],
    ['npm run test:server:unit:all', 'Full a2a-server Vitest'],
    ['npm run test:direct-tests', 'Root Vitest schema guards'],
    ['npm run sim:lint:all', 'Simulation lint --all'],
    ['npm run sim:validate:all', 'Simulation validate --all'],
    ['npm run sim:validate:all:contract', 'Validate + --step-contract'],
    ['npm run scan-promise-bodies', 'proxy_logs promise bodies shape'],
    ['npm run scan-session-responses', 'session server-response.json shape'],
    ['npm run test:gang', 'Mama + Papa orchestrator'],
    ['node tests/direct-tests/e2e-dialog-test.js', 'Client API E2E'],
  ];

  const validatorsMd =
    BANNER +
    `# Validators & gates (generated stub)\n\n` +
    `**Generated:** ${generatedAt}\n\n` +
    mdTable(['Command', 'Surfaces'], validatorsRows) +
    `\n`;

  const indexMd =
    BANNER +
    `# System errors — generated index\n\n` +
    `**Generated:** ${generatedAt}\n\n` +
    `Regenerate: **\`npm run docs:system-errors\`** (repo root)\n\n` +
    `| File | Description |\n|------|-------------|\n` +
    `| [monitor-classifier.generated.md](monitor-classifier.generated.md) | ErrorClassifier patterns + quickFix map |\n` +
    `| [transform-codes.generated.md](transform-codes.generated.md) | transform-execute-validator.ts codes |\n` +
    `| [llm-shape-codes.generated.md](llm-shape-codes.generated.md) | check-llm-execute-shape codes |\n` +
    `| [validators.generated.md](validators.generated.md) | npm commands table |\n` +
    `\n**Human index:** [README.md](README.md)\n`;

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, 'monitor-classifier.generated.md'), monitorMd, 'utf8');
  fs.writeFileSync(path.join(OUT_DIR, 'transform-codes.generated.md'), transformMd, 'utf8');
  fs.writeFileSync(path.join(OUT_DIR, 'llm-shape-codes.generated.md'), llmMd, 'utf8');
  fs.writeFileSync(path.join(OUT_DIR, 'validators.generated.md'), validatorsMd, 'utf8');
  fs.writeFileSync(path.join(OUT_DIR, 'INDEX.generated.md'), indexMd, 'utf8');

  console.log('Wrote docs/system-errors/*.generated.md + INDEX.generated.md');
  console.log('Run: npm run docs:system-errors');
}

function pathToFileUrl(p) {
  const resolved = path.resolve(p);
  if (process.platform === 'win32') {
    return new URL('file:///' + resolved.replace(/\\/g, '/')).href;
  }
  return new URL('file://' + resolved).href;
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
